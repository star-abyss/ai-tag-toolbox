'use strict';
/*
 * 主AI模块 · 门面。对外只有这一个文件。
 *
 *   const 主AI = createMainAiModule({ port })
 *   const 主AI = createMainAiModule({ 根目录, 默认目录, 业务工具 })
 *
 *   // 上层要的那一个
 *   主AI.执行({ 请求?, 预设? })    → { 请求, 预设, 工具表, 模型? }
 *
 *   // 读
 *   主AI.读({ 请求?, 预设? })      → { 表, 启用?, 预设?, 脏, 冻结? }
 *   主AI.表()                     → [ { 标识, 名字, 是本子, 存在, 工具数, 读不懂? } ]
 *   主AI.测({ 请求?, 预设? })      → 与 执行 同形，读草稿
 *   主AI.状态()                   → 体检
 *
 *   // 改（都作用在草稿上；落下要按 存）
 *   主AI.预设({ 动作:'新建'|'复制'|'导入'|'改名'|'删'|'导出'|'改'|'换', … })
 *   主AI.工具({ 动作:'加'|'改'|'删'|'移'|'重置', 预设, … })
 *   主AI.存()  ·  主AI.丢()  ·  主AI.重读()
 *
 *   // 动作表与清单
 *   主AI.run(动作, 参数)
 *   主AI.actions
 *   主AI.describe()
 *
 * 读与改都直接给结果（端口是同步的）。
 * 失败一律 { ok:false, reason, code }。
 */
const { createCore, ERR } = require('./core.js');
const { checkPort, PORT_METHODS } = require('./port.js');
const { createFileAdapter } = require('./adapter-file.js');

const ok = (data) => ({ ok: true, data: data === undefined ? null : data });
const fail = (码, 话) => ({ ok: false, reason: `${码}: ${话}`, code: 码 });

/** 动作表。每一行：名字 → { 摘要, 参数, 说明, 做 }。 */
function 建动作表(core) {
  const 预设说明 = '预设标识：用户那套是 ps1 / ps2，只读默认是 $默认:主AI';
  const 请求说明 = '请求名，如 主AI / 翻译 / 识图；由调用方定，本模块不建对照表';

  return {
    '执行': {
      摘要: '这次这套预设的工具表与模型配置；只读存档',
      参数: ['请求?', '预设?'],
      说明: {
        请求: `${请求说明}。只用来查"这个请求启用了哪几套"；没给就用默认那套`,
        预设: `${预设说明}。给了就用它，指不到就失败（不回落）`,
      },
      做: ({ 请求, 预设 }) => core.执行({ 请求, 预设 }),
    },

    '读': {
      摘要: '表 + 某个请求启用了哪几套 + 那套预设配置 + 草稿状态',
      参数: ['请求?', '预设?'],
      说明: { 请求: 请求说明, 预设: 预设说明 },
      做: ({ 请求, 预设 }) => core.读({ 请求, 预设 }),
    },

    '表': {
      摘要: '全部预设（只读默认 + 用户那套），按名字排序',
      参数: [],
      说明: {},
      做: () => ok(core.表()),
    },

    '测': {
      摘要: '这次会把什么交出去（读草稿，与 执行 同形）',
      参数: ['请求?', '预设?'],
      说明: { 请求: 请求说明, 预设: 预设说明 },
      做: ({ 请求, 预设 }) => core.测({ 请求, 预设 }),
    },

    '预设': {
      摘要: '预设：新建 / 复制 / 导入 / 改名 / 删 / 导出 / 改 / 换',
      参数: ['动作', '请求?', '预设?', '名字?', '源?', '内容?', '一套?', '启用?', 'model?', 'runtime?'],
      说明: {
        动作: '新建 | 复制 | 导入 | 改名 | 删 | 导出 | 改 | 换',
        请求: `换 / 新建 / 复制 / 导入 用。${请求说明}`,
        预设: 预设说明,
        名字: '新建 / 复制 / 导入 / 改名 用；撞名时自动加号',
        源: '新建 / 复制 用：从哪套拷。不填＝从只读默认抄一份快照',
        内容: '导入用：预设文件的文本',
        一套: '导入用：已解析的对象（与 内容 二选一）',
        启用: '换用：一串预设标识；一套都不启用就给空数组',
        model: '改用：{ 走, 模型 }',
        runtime: '改用：给模型的附加文本对象；按给出的字段原样覆盖，空串有效',
      },
      做: (参数) => core.预设(参数),
    },

    '工具': {
      摘要: '调整当前业务工具的摘要、参数文本、启用状态与顺序；schema结构由业务定义',
      参数: ['动作', '预设', '名字?', '启用?', '摘要?', '参数?', '说明?', '方向?', '到?'],
      说明: {
        动作: '加 | 改 | 删 | 移 | 重置',
        预设: 预设说明,
        名字: '当前业务工具表中的名字；不能通过名字指向模块动作',
        启用: '改用：停用给 false；启用给 true',
        摘要: '改用：工具给模型看的完整摘要；空串会清空；随预设保存',
        参数: '改用：递归读取各层 description 文本；类型、必填、字段与schema结构由业务定义',
        说明: '改用：顶层参数的 description 文本；空串有效；随预设保存',
        方向: '移用：上 | 下',
        到: '移用：目标序号',
      },
      做: (参数) => core.工具(参数),
    },

    '存': { 摘要: '草稿写进端口', 参数: [], 说明: {}, 做: () => core.存() },
    '丢': { 摘要: '草稿丢回存档', 参数: [], 说明: {}, 做: () => core.丢() },
    '重读': { 摘要: '重读端口', 参数: [], 说明: {}, 做: () => core.重读() },
    '状态': { 摘要: '体检：几套预设、默认工具表几条、有没有认不出的动作', 参数: [], 说明: {}, 做: () => core.状态() },
  };
}

/**
 * 装配。
 *   { port }                              端口由装配层递进来
 *   { 根目录, 默认目录, 业务工具? }          内部装文件适配器
 */
function createMainAiModule(选项 = {}) {
  let port = 选项.port;
  if (!port) {
    const 根目录 = 选项.根目录;
    const 默认目录 = 选项.默认目录;
    if (typeof 根目录 !== 'string' || !根目录.trim() || typeof 默认目录 !== 'string' || !默认目录.trim()) {
      throw new Error(`${ERR.BAD_ARGUMENT}: 要么递端口 createMainAiModule({ port })，要么给位置 createMainAiModule({ 根目录, 默认目录 })`);
    }
    port = createFileAdapter({ root: 根目录, 默认目录, 业务工具: 选项.业务工具 });
  }
  const 门 = checkPort(port);
  if (!门.ok) throw new Error(`端口不合格：${门.reason}（要有 ${PORT_METHODS.join(' / ')}）`);

  const core = createCore({ port });
  const 动作表 = 建动作表(core);

  /** 走一个动作。 */
  function run(名字, 参数 = {}) {
    const 动作 = 动作表[名字];
    if (!动作) return fail(ERR.BAD_ARGUMENT, `没有这个动作：${名字}`);
    try {
      const 结果 = 动作.做(参数 || {});
      if (!结果 || typeof 结果 !== 'object') return ok(结果);
      return 结果;
    } catch (error) {
      return fail(ERR.WRITE_FAILED, (error && error.message) || '动作执行出错');
    }
  }

  /** 动作清单。 */
  function describe() {
    return Object.entries(动作表).map(([名字, 动作]) => ({
      动作: 名字,
      摘要: 动作.摘要,
      参数: 动作.参数,
      说明: 动作.说明,
    }));
  }

  /** 直呼式：成功给数据，失败给 null。 */
  const 直呼 = (名字) => (参数) => {
    const 结果 = run(名字, 参数);
    return 结果 && 结果.ok ? 结果.data : null;
  };

  const facade = {
    run,
    actions: Object.freeze(Object.keys(动作表)),
    describe,

    执行: 直呼('执行'),
    读: 直呼('读'),
    表: 直呼('表'),
    测: 直呼('测'),
    预设: 直呼('预设'),
    工具: 直呼('工具'),
    存: 直呼('存'),
    丢: 直呼('丢'),
    重读: 直呼('重读'),
    状态: 直呼('状态'),

    ERR: Object.freeze({ ...ERR }),
  };

  return Object.freeze(facade);
}

module.exports = { createMainAiModule };
