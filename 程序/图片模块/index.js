/**
 * 装配。
 *   { port }                                      端口由装配层递进来
 *   { 根目录 }                                    内部装文件适配器
 *   { 处理图片, 交回收站, 新标识, 校验和, 现在 }     依赖由装配层递进来
 */
function createImageModule(选项 = {}) {
  if (选项.接收作用域 !== undefined && typeof 选项.接收作用域 !== 'function') throw new Error('接收作用域 必须是函数');
  let port = 选项.port;
  if (!port) {
    const 根 = 选项.根目录;
    if (typeof 根 !== 'string' || !根.trim()) {
      throw new Error(`${ERR.ROOT_REQUIRED}: 要么递端口 createImageModule({ port })，要么给位置 createImageModule({ 根目录 })`);
    }
    port = createFileAdapter({ root: 根, trashItem: 选项.交回收站 });
  } else if (选项.根目录 !== undefined && 选项.根目录 !== null && String(选项.根目录).trim() === '') {
    throw new Error(`${ERR.ROOT_REQUIRED}: 根目录不能是空的`);
  }
  const 门 = checkPort(port);
  if (!门.ok) throw new Error(`端口不合格：${门.reason}（要有 ${PORT_METHODS.join(' / ')}）`);

  const core = createCore({
    port,
    处理图片: 选项.处理图片 || null,
    交回收站: 选项.交回收站 || null,
    新标识: 选项.新标识 || null,
    校验和: 选项.校验和 || null,
    现在: 选项.现在 || null,
    接收作用域: 选项.接收作用域,
  });

  const 动作表 = 建动作表(core);

  /** 走一个动作。 */
  function run(名字, 参数 = {}) {
    const 动作 = 动作表[名字];
    if (!动作) return fail(ERR.BAD_ARGUMENT, `没有这个动作：${名字}`);
    try {
      const 结果 = 动作.做(参数 || {});
      if (!结果 || typeof 结果 !== 'object') return ok(结果);
      return 结果;
    } catch (error) {
      return fail(ERR.WRITE_FAILED, (error && error.message) || '动作执行出错');
    }
  }

  /** 动作清单。 */
  function describe() {
    return Object.entries(动作表).map(([名字, 动作]) => ({
      动作: 名字,
      摘要: 动作.摘要,
      参数: 动作.参数,
      说明: 动作.说明,
    }));
  }

  /** 直呼式：成功给数据，失败给 null。写操作返回 Promise。 */
  const 直呼 = (名字) => (参数) => 解包(run(名字, 参数));

  /** 统一解包：同步结果直接取，Promise 等它。失败给 null。 */
  function 解包(结果) {
    if (结果 && typeof 结果.then === 'function') return 结果.then((x) => (x && x.ok ? x.data : null));
    return 结果 && 结果.ok ? 结果.data : null;
  }

  /** 工作区能力组：只给识图模块，只有一个 清空。 */
  function 工作区能力() {
    return Object.freeze({
      清空: () => core.清空({ 作用域: { 存放地: 'vision' } }),
    });
  }

  const facade = {
    run,
    actions: Object.freeze(Object.keys(动作表)),
    describe,

    列: 直呼('列'),
    列会话图: (输入) => {
      const 结果 = run('列会话图', 输入 || {});
      return 结果 && typeof 结果.then === 'function'
        ? 结果.then((x) => (x && x.ok ? x.data : null))
        : (结果 && 结果.ok ? 结果.data : null);
    },
    按图号取详情: (输入) => {
      const 结果 = run('按图号取详情', 输入 || {});
      return 结果 && typeof 结果.then === 'function'
        ? 结果.then((x) => (x && x.ok ? x.data : null))
        : (结果 && 结果.ok ? 结果.data : null);
    },
    导入会话图: (输入) => {
      const 结果 = run('导入会话图', 输入 || {});
      return 结果 && typeof 结果.then === 'function'
        ? 结果.then((x) => (x && x.ok ? x.data : null))
        : (结果 && 结果.ok ? 结果.data : null);
    },
    恢复会话图号: (输入) => {
      const 结果 = run('恢复会话图号', 输入 || {});
      return 结果 && typeof 结果.then === 'function'
        ? 结果.then((x) => (x && x.ok ? x.data : null))
        : (结果 && 结果.ok ? 结果.data : null);
    },
    取详情: 直呼('取详情'),
    取内容: 直呼('取内容'),
    取地址: 直呼('取地址'),
    存: 直呼('存'),
    改: 直呼('改'),
    删: 直呼('删'),
    清空: 直呼('清空'),

    维护: (输入) => 解包(run((输入 && 输入.动作) === '清理' ? '维护.清理' : '维护.报告', {})),
    表: (输入) => 解包(run((输入 && 输入.表) === '分类' ? '表.分类' : '表.收藏', 输入 || {})),
    工作区能力,

    ERR: Object.freeze({ ...ERR }),
    存放地: Object.freeze(['session', 'gallery', 'vision']),
    变体: Object.freeze(['original', 'preview', 'thumbnail']),
  };

  return Object.freeze(facade);
}

module.exports = { createImageModule };
