'use strict';
/*
 * 图片模块 · 门面。对外只有这一个文件。
 *
 *   const 图片 = createImageModule({ port, 处理图片, 交回收站 })
 *   const 图片 = createImageModule({ 根目录, 处理图片, 交回收站 })
 *
 *   // 图片操作
 *   图片.列({ 作用域 })
 *   图片.取详情({ 引用 })
 *   图片.取内容({ 引用, 变体? })
 *   图片.取地址({ 引用, 变体? })
 *   图片.存({ 作用域, 字节 | dataUrl, 文件名, mime, 来源?, 显示名?, 元数据? })
 *   图片.改({ 引用, 显示名?, 元数据? })
 *   图片.删({ 引用 })
 *   图片.清空({ 作用域 })
 *
 *   // 动作表与清单
 *   图片.run(动作, 参数)
 *   图片.actions
 *   图片.describe()
 *
 *   // 内部
 *   图片.维护({ 动作:'报告'|'清理' })
 *   图片.表({ 表, 动作, 类?, 标识?, 名?, 配色? })
 *   图片.工作区能力()            只有 { 清空 }
 *
 * 列 / 取详情 / 取内容 / 取地址 直接给结果。
 * 存 / 改 / 删 / 清空 / 表 走写队列，返回 Promise。
 * 失败一律 { ok:false, reason, code }。
 *
 * 引用与作用域用英文键（作用域 / 条目ID / 存放地 / 会话ID）；动作名与回执字段用中文。
 */

const { createCore, ERR } = require('./core.js');
const { checkPort, PORT_METHODS } = require('./port.js');
const { createFileAdapter } = require('./adapter-file.js');

const ok = (data) => ({ ok: true, data: data === undefined ? null : data });
const fail = (码, 话) => ({ ok: false, reason: `${码}: ${话}`, code: 码 });

